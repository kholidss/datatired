#!/bin/sh
# Regenerates src/icons.rs from assets/icons/*.svg (camelCase file -> SCREAMING_SNAKE const).
cd "$(dirname "$0")/.."
{
  echo '//! SVG icons: New UI set from intellij-community (Apache-2.0) + own DB-specific ones.'
  echo '//! Generated by scripts/icons.sh.'
  echo
  echo 'use egui::{include_image, ImageSource};'
  echo
  for f in $(ls assets/icons/*.svg | sort); do
    n=$(basename "$f" .svg)
    c=$(echo "$n" | sed -E 's/([a-z0-9])([A-Z])/\1_\2/g' | tr a-z A-Z)
    echo "pub const $c: ImageSource<'static> = include_image!(\"../assets/icons/$n.svg\");"
  done
} > src/icons.rs
